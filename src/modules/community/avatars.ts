/** 预设头像总数（avatarIndex 有效范围 0 ~ COUNT-1） */
export const COMMUNITY_AVATAR_COUNT = 1181

/**
 * 按索引取头像 emoji；越界 / 未设置时回退第一个
 */
export function getCommunityAvatar(index: number | null | undefined): string {
  if (index == null || index < 0 || index >= COMMUNITY_AVATAR_COUNT) {
    return COMMUNITY_AVATARS[0]
  }
  return COMMUNITY_AVATARS[index]
}
